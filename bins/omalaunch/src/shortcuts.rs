//! Single-source keyboard shortcut table.
//!
//! Every shortcut in the app is registered from [`SHORTCUTS`], rendered into
//! the `?` overlay from [`SHORTCUTS`], and documented by `--dump-shortcuts`
//! from [`SHORTCUTS`]. Add a row here and all three follow; the snapshot
//! test fails on drift.

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Action {
    Down,
    Up,
    First,
    Last,
    PageDown,
    PageUp,
    Search,
    Launch,
    Play,
    Add,
    Update,
    Remove,
    Favorite,
    Hide,
    Settings,
    Help,
    Clear,
}

#[derive(Debug, Clone, Copy)]
pub struct Shortcut {
    pub action: Action,
    /// GTK accelerator string, e.g. `"j"`, `"slash"`, `"Return"`.
    pub keys: &'static str,
    pub description: &'static str,
}

