/// Render the table as Markdown (used by `--dump-shortcuts` and docs).
pub fn dump_markdown() -> String {
    let mut out = String::from("# Omalaunch keyboard shortcuts\n\n");
    out.push_str("<!-- GENERATED by `omalaunch --dump-shortcuts`. Do not hand-edit. -->\n\n");
    out.push_str("| Keys | Action |\n| --- | --- |\n");
    for row in SHORTCUTS {
        out.push_str(&format!("| `{}` | {} |\n", row.keys, row.description));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn table_matches_committed_snapshot() {
        let fixture = include_str!("../tests/fixtures/shortcuts.md");
        assert_eq!(
            dump_markdown(),
            fixture,
            "run `omalaunch --dump-shortcuts` to refresh"
        );
    }

    #[test]
    fn every_action_has_at_least_one_binding() {
        let mut seen = HashSet::new();
        for row in SHORTCUTS {
            seen.insert(row.action);
        }
        for action in [
            Action::Down,
            Action::Up,
            Action::First,
            Action::Last,
            Action::PageDown,
            Action::PageUp,
            Action::Search,
            Action::Launch,
            Action::Play,
            Action::Add,
            Action::Update,
            Action::Remove,
            Action::Favorite,
            Action::Hide,
            Action::Settings,
            Action::Help,
            Action::Clear,
        ] {
            assert!(seen.contains(&action), "unbound action: {action:?}");
        }
    }

    #[test]
    fn no_duplicate_bindings() {
        let mut seen = HashSet::new();
        for row in SHORTCUTS {
            assert!(seen.insert(row.keys), "duplicate binding: {}", row.keys);
        }
    }
}
